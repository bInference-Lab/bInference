/** The two factories a holder distributor's address follows from. */
export interface DistributorFactories {
  /** BrewDistributorFactory, which deploys each token's distributor. */
  readonly distributorFactory: Address;
  /** BrewFactory, which the distributor takes as its own factory. */
  readonly brewFactory: Address;
}

/**
 * The address BrewDistributorFactory gives a token's holder distributor (decision 0283): CREATE2
 * from the distributor factory, with the token's address as the salt and the distributor's
 * creation code with BrewFactory and the token as its arguments, as its `predict` reads.
 */
export function distributorAddressOf(factories: DistributorFactories, token: Address): Address {
  const args = encodeAbiParameters(parseAbiParameters("address, address"), [
    factories.brewFactory,
    token,
  ]);
  return getContractAddress({
    opcode: "CREATE2",
    from: factories.distributorFactory,
    salt: pad(token),
    bytecode: concat([creationCode, args]),
  });
}
