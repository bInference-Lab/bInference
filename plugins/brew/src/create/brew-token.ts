/** What a BrewToken's address commits to: its factory, its creator, the salt and its words. */
export interface TokenCreate {
  readonly factory: Address;
  readonly creator: Address;
  readonly name: string;
  readonly symbol: string;
  readonly totalSupply: bigint;
  readonly metadataURI: string;
}

/** The hash of the token's creation code with its constructor's arguments. */
export function tokenInitCodeHash(create: TokenCreate): Hex {
  const args = encodeAbiParameters(
    parseAbiParameters("string, string, uint256, address, string, address"),
    [
      create.name,
      create.symbol,
      create.totalSupply,
      create.factory,
      create.metadataURI,
      create.creator,
    ],
  );
  return keccak256(concat([creationCode, args]));
}

/** The 32 bytes the factory hashes a caller's salt behind: the creator's address, padded. */
export function saltPrefixOf(creator: Address): Hex {
  return pad(creator);
}

/**
 * The address BrewFactory gives a token launched with `salt`: CREATE2 from the factory, with the
 * salt `keccak256(abi.encode(creator, salt))` and the token's creation code with its arguments.
 */
export function tokenAddressOf(create: TokenCreate, salt: Hex): Address {
  return getContractAddress({
    opcode: "CREATE2",
    from: create.factory,
    salt: keccak256(concat([saltPrefixOf(create.creator), salt])),
    bytecodeHash: tokenInitCodeHash(create),
  });
}
